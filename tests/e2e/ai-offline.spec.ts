import { expect, test } from "@playwright/test";
import { fixtureEmail, fixturePassword } from "./fixtures";

test("private architecture studio stays useful with AI disabled and makes no generation call on load", async ({ page }) => {
  test.skip(process.env.HOLOSTACK_LIVE_AI_SMOKE === "true", "This test uses the default offline Playwright server.");
  const generationCalls: string[] = [];
  let aiStatus: Record<string, unknown> | null = null;
  page.on("request", request => { if (request.url().includes("/api/ai/generate") || request.url().includes("/api/ai/assistant")) generationCalls.push(request.url()); });
  page.on("response", response => { if (response.url().endsWith("/api/ai/status")) void response.json().then(body => { aiStatus = body as Record<string, unknown>; }).catch(() => {}); });
  await page.goto("/signup");
  await page.getByLabel("Your name").fill("Offline AI Test");
  await page.getByLabel("Email address").fill(fixtureEmail());
  const password = fixturePassword();
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByLabel("Confirm password").fill(password);
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/, { timeout: 15_000 });
  await page.getByRole("button", { name: "New project", exact: true }).click();
  await page.getByLabel("Project name", { exact: true }).fill("Offline design workbench");
  await page.getByRole("button", { name: "Create project", exact: true }).click();
  await expect(page).toHaveURL(/\/projects\/[a-f0-9-]+$/);
  await page.getByRole("button", { name: "AI assistant" }).click();
  await expect(page.getByText(/AI features are unavailable right now/)).toBeVisible();
  await expect(page.getByText(/No daily HoloStack limit/)).toBeVisible();
  await expect.poll(() => aiStatus).not.toBeNull();
  expect(aiStatus).toMatchObject({ enabled: false, usage: { todayActions: expect.any(Number) } });
  for (const key of ["models", "model", "provider", "configured", "message"]) expect(aiStatus).not.toHaveProperty(key);
  const aiPanelText = await page.locator("#ai-workbench").innerText();
  expect(aiPanelText).not.toMatch(/Gemini|Google AI|TiDB|PostgreSQL|gemini-/i);
  await expect(page.getByRole("button", { name: "Generate architecture" })).toBeDisabled();
  await page.getByRole("button", { name: "Canvas", exact: true }).click();
  await expect(page.getByRole("button", { name: "Add selected component" })).toBeEnabled();
  expect(generationCalls).toEqual([]);
  await page.goto("/setup");
  const setupText = await page.locator(".setup-main").innerText();
  expect(setupText).not.toMatch(/TiDB|PostgreSQL|Gemini|Google AI|AWS|Vercel|Next\.js|DATABASE_URL|GEMINI_API_KEY/i);
  await expect(page.getByRole("heading", { name: /A reliable foundation/ })).toBeVisible();
});
